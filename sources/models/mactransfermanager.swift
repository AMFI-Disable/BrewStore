import AppKit
import Foundation

struct MacRigPackageBundle: Identifiable, Codable, Hashable, Sendable {
    var id: String {
        name
    }

    let name: String
    let version: String
    let kind: String
    let tap: String?
}

struct MacRigExportBundle: Codable, Sendable {
    let rigName: String
    let macModel: String
    let architecture: String
    let exportDate: Date
    let taps: [String]
    let formulae: [MacRigPackageBundle]
    let casks: [MacRigPackageBundle]
    let masApps: [MacRigPackageBundle]
    let pinnedPackages: [String]
    let brewfileContent: String
    let preferencesJSON: String?

    var totalPackagesCount: Int {
        formulae.count + casks.count + masApps.count
    }

    init(
        rigName: String,
        macModel: String,
        architecture: String,
        exportDate: Date,
        taps: [String],
        formulae: [MacRigPackageBundle],
        casks: [MacRigPackageBundle],
        masApps: [MacRigPackageBundle] = [],
        pinnedPackages: [String],
        brewfileContent: String,
        preferencesJSON: String? = nil
    ) {
        self.rigName = rigName
        self.macModel = macModel
        self.architecture = architecture
        self.exportDate = exportDate
        self.taps = taps
        self.formulae = formulae
        self.casks = casks
        self.masApps = masApps
        self.pinnedPackages = pinnedPackages
        self.brewfileContent = brewfileContent
        self.preferencesJSON = preferencesJSON
    }
}

@MainActor
final class BrewStoreMacTransferManager: ObservableObject {
    static let shared = BrewStoreMacTransferManager()

    @Published var activeExportBundle: MacRigExportBundle?
    @Published var importedBundle: MacRigExportBundle?
    @Published var copySuccessNotification = false
    @Published var isBootstrapping = false
    @Published var bootstrapStatus: String?

    func createRigBundle(manager: HomebrewManager, name: String) -> MacRigExportBundle {
        let hostName = Host.current().localizedName ?? "Mac Rig"
        #if arch(arm64)
            let arch = "arm64"
        #else
            let arch = "x86_64"
        #endif

        let installedFormulae = manager.packages.filter { $0.kind == .formula && $0.isInstalled }
        let installedCasks = manager.packages.filter { $0.kind == .cask && $0.isInstalled }
        let installedMAS = BrewStoreMASManager.shared.installedApps

        let formBundles = installedFormulae.map {
            MacRigPackageBundle(name: $0.id, version: $0.version, kind: "formula", tap: $0.tap)
        }
        let caskBundles = installedCasks.map {
            MacRigPackageBundle(name: $0.id, version: $0.version, kind: "cask", tap: $0.tap)
        }
        let masBundles = installedMAS.map {
            MacRigPackageBundle(name: $0.name, version: $0.installedVersion, kind: "mas", tap: String($0.id))
        }

        let pinned = Array(BrewStorePackagePinningManager.shared.pinnedPackageIDs)
        let taps = manager.taps.map(\.name)

        // Generate enhanced Brewfile with MAS apps
        let brewfileContent = BrewStoreBrewfileParser.generate(
            packages: manager.packages.filter(\.isInstalled),
            taps: manager.taps,
            masApps: installedMAS
        )

        // Preferences JSON
        let prefsJSON: String? = {
            let prefs = BrewStorePreferences.shared
            let dict: [String: Any] = [
                "enableAppCleaner": prefs.enableAppCleaner,
                "isAutoCheckEnabled": prefs.isAutoCheckEnabled,
                "checkIntervalHours": prefs.checkIntervalHours,
                "defaultAppSourcePreference": prefs.defaultAppSourcePreference.rawValue
            ]
            if let data = try? JSONSerialization.data(withJSONObject: dict, options: .prettyPrinted) {
                return String(data: data, encoding: .utf8)
            }
            return nil
        }()

        let bundle = MacRigExportBundle(
            rigName: name.isEmpty ? hostName : name,
            macModel: hostName,
            architecture: arch,
            exportDate: Date(),
            taps: taps,
            formulae: formBundles,
            casks: caskBundles,
            masApps: masBundles,
            pinnedPackages: pinned,
            brewfileContent: brewfileContent,
            preferencesJSON: prefsJSON
        )

        self.activeExportBundle = bundle
        return bundle
    }

    func generateBootstrapScript(bundle: MacRigExportBundle) -> String {
        var script = """
        #!/usr/bin/env bash
        # 🚀 1-Command Mac Blueprint Bootstrap Script for \(bundle.rigName)
        # Generated by BrewStore (https://github.com/amfi-disable/BrewStore)

        set -e
        echo "🍺 Bootstrapping Mac Blueprint for \(bundle.rigName)..."

        # 1. Install Homebrew if missing
        if ! command -v brew &> /dev/null; then
            echo "==> Installing Homebrew..."
            /bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)"
            eval "$(/opt/homebrew/bin/brew shellenv 2>/dev/null || /usr/local/bin/brew shellenv 2>/dev/null)"
        fi

        # 2. Add Taps
        \(bundle.taps.map { "brew tap \($0)" }.joined(separator: "\n"))

        # 3. Install CLI Formulae
        \(bundle.formulae.map { "brew install \($0.name)" }.joined(separator: "\n"))

        # 4. Install GUI Casks
        \(bundle.casks.map { "brew install --cask \($0.name)" }.joined(separator: "\n"))

        """

        if !bundle.masApps.isEmpty {
            script += """

            # 5. Mac App Store Applications
            if ! command -v mas &> /dev/null; then
                echo "==> Installing 'mas' CLI..."
                brew install mas
            fi
            \(bundle.masApps.compactMap { app -> String? in
                guard let tap = app.tap, !tap.isEmpty else { return nil }
                return "mas install \(tap) # \(app.name)"
            }.joined(separator: "\n"))

            """
        }

        if !bundle.pinnedPackages.isEmpty {
            script += """

            # 6. Pin Versions
            \(bundle.pinnedPackages.map { "brew pin \($0)" }.joined(separator: "\n"))

            """
        }

        script += """

        echo "✅ Setup complete! \(bundle.totalPackagesCount) applications and packages successfully configured."
        """

        return script
    }

    func bootstrapMac(bundle: MacRigExportBundle, manager: HomebrewManager) {
        isBootstrapping = true
        bootstrapStatus = "Starting Mac Blueprint restore…"

        Task { @MainActor in
            // 1. Taps
            let installedTapNames = Set(manager.taps.map { $0.name.lowercased() })
            for tap in bundle.taps where !installedTapNames.contains(tap.lowercased()) {
                self.bootstrapStatus = "Adding tap \(tap)…"
                manager.tap(name: tap)
            }

            // 2. Missing Formulae and Casks
            let installedSet = Set(manager.packages.filter(\.isInstalled).map { $0.id.lowercased() })
            var toInstall: [BrewStorePackage] = []

            for f in bundle.formulae where !installedSet.contains(f.name.lowercased()) {
                let pkg = manager.packages.first { $0.id.lowercased() == f.name.lowercased() } ?? BrewStorePackage(
                    id: f.name,
                    name: f.name,
                    description: "Imported from Mac Blueprint",
                    homepage: "",
                    version: f.version,
                    kind: .formula,
                    isInstalled: false,
                    isOutdated: false
                )
                toInstall.append(pkg)
            }

            for c in bundle.casks where !installedSet.contains(c.name.lowercased()) {
                let pkg = manager.packages.first { $0.id.lowercased() == c.name.lowercased() } ?? BrewStorePackage(
                    id: c.name,
                    name: c.name,
                    description: "Imported from Mac Blueprint",
                    homepage: "",
                    version: c.version,
                    kind: .cask,
                    isInstalled: false,
                    isOutdated: false
                )
                toInstall.append(pkg)
            }

            if !toInstall.isEmpty {
                self.bootstrapStatus = "Installing \(toInstall.count) Homebrew packages…"
                manager.batchPerform(packages: toInstall, action: .install)
            }

            // 3. MAS Apps
            let installedMASIDs = Set(BrewStoreMASManager.shared.installedApps.map(\.id))
            for app in bundle.masApps {
                if let masID = app.tap, !masID.isEmpty, !installedMASIDs.contains(masID) {
                    self.bootstrapStatus = "Installing Mac App Store app: \(app.name)…"
                    BrewStoreMASManager.shared.installApp(id: masID, name: app.name)
                }
            }

            self.isBootstrapping = false
            self.bootstrapStatus = "Mac Blueprint setup complete!"
        }
    }

    func exportBundleToFile(bundle: MacRigExportBundle) -> URL? {
        let tempDir = FileManager.default.temporaryDirectory
        let safeName = bundle.rigName
            .replacingOccurrences(of: " ", with: "-")
            .replacingOccurrences(of: "/", with: "-")
        let fileURL = tempDir.appendingPathComponent("\(safeName).brewstore")
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        encoder.dateEncodingStrategy = .iso8601

        guard let data = try? encoder.encode(bundle) else { return nil }
        try? data.write(to: fileURL)
        return fileURL
    }

    func importBundleFromFile(url: URL) -> MacRigExportBundle? {
        guard let data = try? Data(contentsOf: url) else { return nil }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        if let bundle = try? decoder.decode(MacRigExportBundle.self, from: data) {
            self.importedBundle = bundle
            return bundle
        }
        return nil
    }
}
