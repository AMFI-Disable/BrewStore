import Foundation

struct BrewStoreBrewfileMASEntry: Hashable, Codable, Sendable {
    let name: String
    let id: String
}

struct BrewStoreBrewfile: Hashable, Sendable {
    let formulae: Set<String>
    let casks: Set<String>
    let taps: Set<String>
    let masApps: [BrewStoreBrewfileMASEntry]

    init(
        formulae: Set<String>,
        casks: Set<String>,
        taps: Set<String>,
        masApps: [BrewStoreBrewfileMASEntry] = []
    ) {
        self.formulae = formulae
        self.casks = casks
        self.taps = taps
        self.masApps = masApps
    }

    var packageCount: Int {
        formulae.count + casks.count + masApps.count
    }
}

struct BrewStoreBrewfileDiff: Hashable, Sendable {
    let missingFormulae: [String]
    let missingCasks: [String]
    let missingTaps: [String]
    let extraInstalledFormulae: [String]
    let extraInstalledCasks: [String]

    var changeCount: Int {
        missingFormulae.count + missingCasks.count + missingTaps.count
    }
}

enum BrewStoreBrewfileParser {
    static func parse(_ contents: String) -> BrewStoreBrewfile {
        var formulae = Set<String>()
        var casks = Set<String>()
        var taps = Set<String>()
        var masApps: [BrewStoreBrewfileMASEntry] = []

        for rawLine in contents.components(separatedBy: .newlines) {
            let line = rawLine.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !line.isEmpty, !line.hasPrefix("#") else { continue }

            if line.hasPrefix("mas ") {
                let rest = line.dropFirst(4).trimmingCharacters(in: .whitespaces)
                if let firstQuote = rest.firstIndex(of: "\"") {
                    let afterFirst = rest[rest.index(after: firstQuote)...]
                    if let secondQuote = afterFirst.firstIndex(of: "\"") {
                        let appName = String(afterFirst[..<secondQuote])
                        let afterSecond = afterFirst[afterFirst.index(after: secondQuote)...]
                        if let idRange = afterSecond.range(of: "id:") {
                            let idStr = afterSecond[idRange.upperBound...]
                                .trimmingCharacters(in: .whitespacesAndNewlines)
                            if !idStr.isEmpty {
                                masApps.append(BrewStoreBrewfileMASEntry(name: appName, id: idStr))
                            }
                        }
                    }
                }
                continue
            }

            let parts = line.split(separator: " ", maxSplits: 1).map(String.init)
            guard parts.count == 2 else { continue }
            let value = parts[1].trimmingCharacters(in: .whitespacesAndNewlines)
            guard value.hasPrefix("\""), value.hasSuffix("\"") else { continue }
            let name = String(value.dropFirst().dropLast())
            guard !name.isEmpty else { continue }
            switch parts[0] {
            case "brew": formulae.insert(name)
            case "cask": casks.insert(name)
            case "tap": taps.insert(name)
            default: break
            }
        }
        return BrewStoreBrewfile(formulae: formulae, casks: casks, taps: taps, masApps: masApps)
    }

    static func diff(
        _ brewfile: BrewStoreBrewfile,
        installedPackages: [BrewStorePackage],
        installedTaps: [BrewStoreTap]
    ) -> BrewStoreBrewfileDiff {
        let installedFormulae = Set(installedPackages.filter { $0.kind == .formula && $0.isInstalled }.map(\.id))
        let installedCasks = Set(installedPackages.filter { $0.kind == .cask && $0.isInstalled }.map(\.id))
        let installedTapNames = Set(installedTaps.map(\.name))
        return BrewStoreBrewfileDiff(
            missingFormulae: brewfile.formulae.subtracting(installedFormulae).sorted(),
            missingCasks: brewfile.casks.subtracting(installedCasks).sorted(),
            missingTaps: brewfile.taps.subtracting(installedTapNames).sorted(),
            extraInstalledFormulae: installedFormulae.subtracting(brewfile.formulae).sorted(),
            extraInstalledCasks: installedCasks.subtracting(brewfile.casks).sorted()
        )
    }

    static func generate(
        packages: [BrewStorePackage],
        taps: [BrewStoreTap] = [],
        masApps: [MASApp] = []
    ) -> String {
        var lines: [String] = [
            "# Brewfile generated by BrewStore",
            "# https://github.com/amfi-disable/BrewStore",
            ""
        ]

        let sortedTaps = taps.map(\.name).sorted()
        if !sortedTaps.isEmpty {
            for tap in sortedTaps {
                lines.append("tap \"\(tap)\"")
            }
            lines.append("")
        }

        let casks = packages.filter { $0.kind == .cask && $0.isInstalled }.sorted { $0.id < $1.id }
        if !casks.isEmpty {
            for cask in casks {
                lines.append("cask \"\(cask.id)\"")
            }
            lines.append("")
        }

        let formulae = packages.filter { $0.kind == .formula && $0.isInstalled }.sorted { $0.id < $1.id }
        if !formulae.isEmpty {
            for formula in formulae {
                lines.append("brew \"\(formula.id)\"")
            }
            lines.append("")
        }

        if !masApps.isEmpty {
            lines.append("# Mac App Store Applications")
            for app in masApps.sorted(by: { $0.name < $1.name }) {
                lines.append("mas \"\(app.name)\", id: \(app.id)")
            }
            lines.append("")
        }

        return lines.joined(separator: "\n")
    }
}
