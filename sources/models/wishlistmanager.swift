import Foundation

struct BrewStoreCollection: Identifiable, Codable, Hashable {
    var id: UUID = UUID()
    var title: String
    var description: String
    var packageIDs: [String]
    var colorName: String
}

@MainActor
final class BrewStoreWishlistManager: ObservableObject {
    static let shared = BrewStoreWishlistManager()

    private let defaults = UserDefaults.standard
    private let wishlistKey = "pref_wishlist_package_ids"
    private let collectionsKey = "pref_user_custom_collections"

    @Published var wishlistIDs: Set<String> = [] {
        didSet {
            defaults.set(Array(wishlistIDs), forKey: wishlistKey)
        }
    }

    @Published var collections: [BrewStoreCollection] = [] {
        didSet {
            if let data = try? JSONEncoder().encode(collections) {
                defaults.set(data, forKey: collectionsKey)
            }
        }
    }

    init() {
        if let savedWishlist = defaults.stringArray(forKey: wishlistKey) {
            self.wishlistIDs = Set(savedWishlist)
        } else {
            self.wishlistIDs = []
        }

        if let data = defaults.data(forKey: collectionsKey),
           let savedCollections = try? JSONDecoder().decode([BrewStoreCollection].self, from: data) {
            self.collections = savedCollections
        } else {
            self.collections = []
        }
    }

    func toggleWishlist(id: String) {
        if wishlistIDs.contains(id) {
            wishlistIDs.remove(id)
        } else {
            wishlistIDs.insert(id)
        }
    }

    func isWishlisted(id: String) -> Bool {
        wishlistIDs.contains(id)
    }

    func createCollection(title: String, description: String, packageIDs: [String], colorName: String = "blue") {
        let col = BrewStoreCollection(title: title, description: description, packageIDs: packageIDs, colorName: colorName)
        collections.append(col)
    }

    func deleteCollection(id: UUID) {
        collections.removeAll { $0.id == id }
    }

    func resetWishlistAndCollections() {
        wishlistIDs.removeAll()
        collections.removeAll()
        defaults.removeObject(forKey: wishlistKey)
        defaults.removeObject(forKey: collectionsKey)
    }

    func exportToBrewfile(packageIDs: [String], manager: HomebrewManager, knownCaskIDs: Set<String> = []) -> String {
        var lines: [String] = [
            "# Brewfile generated by BrewStore Wishlist & Collections",
            "# Exported on \(Date().formatted(date: .abbreviated, time: .shortened))",
            ""
        ]

        var casks: [String] = []
        var formulae: [String] = []

        for id in packageIDs {
            if let pkg = manager.packages.first(where: { $0.id == id }) {
                if pkg.kind == .cask {
                    casks.append(id)
                } else {
                    formulae.append(id)
                }
            } else if knownCaskIDs.contains(id) {
                casks.append(id)
            } else {
                formulae.append(id)
            }
        }

        if !casks.isEmpty {
            lines.append("# Applications (Casks)")
            for c in casks.sorted() {
                lines.append("cask \"\(c)\"")
            }
            lines.append("")
        }

        if !formulae.isEmpty {
            lines.append("# Command-line Binaries (Formulae)")
            for f in formulae.sorted() {
                lines.append("brew \"\(f)\"")
            }
            lines.append("")
        }

        return lines.joined(separator: "\n")
    }
}
